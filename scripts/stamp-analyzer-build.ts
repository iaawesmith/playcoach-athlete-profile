// Run before deploying analyze-athlete-video: writes the build stamp
// (short commit + UTC date) the analyzer records on every run.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const commit = (() => {
  try {
    return execSync("git rev-parse --short HEAD").toString().trim();
  } catch {
    return "unknown";
  }
})();
const date = new Date().toISOString().slice(0, 10);
const stamp = `${commit}-${date}`;
writeFileSync(
  "supabase/functions/analyze-athlete-video/build.ts",
  `// Generated by scripts/stamp-analyzer-build.ts at deploy. Do not edit.\nexport const ANALYZER_BUILD = '${stamp}'\n`,
);
process.stdout.write(`${stamp}\n`);
